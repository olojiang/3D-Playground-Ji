export const MESSAGES: Record<Lang, Record<MessageKey, string>> = { zh, en };

export function translate(lang: Lang, key: MessageKey, vars?: Record<string, string | number>): string {
  const s = MESSAGES[lang][key] ?? MESSAGES.zh[key] ?? key;
  return vars ? s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m)) : s;
}

export const placeholders = (s: string) => [...s.matchAll(/\{(\w+)\}/g)].map((m) => m[1]).sort();

/** "3 分钟前" / "3 min ago" */
export function timeAgo(lang: Lang, ts: number, now = Date.now()): string {
  const m = Math.floor((now - ts) / 60000);
  if (m < 1) return translate(lang, "common.justNow");
  if (m < 60) return translate(lang, "common.minutesAgo", { n: m });
  const h = Math.floor(m / 60);
  if (h < 24) return translate(lang, "common.hoursAgo", { n: h });
  return translate(lang, "common.daysAgo", { n: Math.floor(h / 24) });
}
